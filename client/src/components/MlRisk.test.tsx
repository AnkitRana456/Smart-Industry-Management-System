import { screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { beforeEach, describe, expect, it, vi } from 'vitest';
import type { MlPrediction, MlStatus } from '../lib/types';
import { apiMock, resetApi, routeGet } from '../test/mockApi';
import { apiError, machine, ok, renderWithApp } from '../test/utils';
import MlRiskPanel from './MlRisk';

vi.mock('../lib/api', async () => (await import('../test/mockApi')).module);

const status = (over: Partial<MlStatus> = {}): MlStatus => ({
  enabled: true, reachable: true, modelLoaded: true, modelVersion: 'logistic-regression-b1684830', algorithm: 'logistic-regression',
  dataSource: 'synthetic', trainedAt: '2026-10-29T06:00:00Z', bands: { mediumFrom: 0.1, highFrom: 0.3 },
  metrics: { rocAuc: 0.8014, brier: 0.0707, baseRate: 0.0977, references: { generatorCeilingRocAuc: 0.8015 } },
  limitations: ['Trained on synthetic data generated by a documented rule set.', 'Not validated predictions of real machine failures.'],
  ...over,
});

const prediction = (over: Partial<MlPrediction> = {}): MlPrediction => ({
  predictionId: 'p1', machineId: 'm1', risk: 'High', probability: 0.4519, modelVersion: 'logistic-regression-b1684830', dataSource: 'synthetic',
  predictedAt: '2026-10-29T06:10:00Z',
  topFactors: [
    { feature: 'toolWearMin', label: 'Tool wear', value: 222, unit: 'min', effect: 0.2, direction: 'raises' },
    { feature: 'vibrationMms', label: 'Vibration', value: 4.35, unit: 'mm/s', effect: 0.15, direction: 'raises' },
    { feature: 'runHours', label: 'Run hours', value: 800, unit: 'h', effect: -0.01, direction: 'lowers' },
  ],
  warnings: [],
  ...over,
});

const panel = () => renderWithApp(<MlRiskPanel machine={machine()} />);
beforeEach(() => resetApi());

describe('when the model service is not configured', () => {
  it('shows nothing at all', async () => {
    routeGet({ '/ml/status': { enabled: false, reachable: false }, '/machines/m1/ml-predictions': [] });
    panel();
    await waitFor(() => expect(apiMock.get).toHaveBeenCalledWith('/ml/status'));
    expect(screen.queryByLabelText('Statistical risk model')).not.toBeInTheDocument();
    expect(apiMock.get).not.toHaveBeenCalledWith('/machines/m1/ml-predictions');
  });
});

describe('when the service is configured', () => {
  it('always says what the model was trained on, before any score exists', async () => {
    routeGet({ '/ml/status': status(), '/machines/m1/ml-predictions': [] });
    panel();
    expect(await screen.findByText('Trained on synthetic data')).toBeInTheDocument();
    expect(await screen.findByText(/Not scored yet/)).toBeInTheDocument();
    expect(screen.getByRole('button', { name: 'Score now' })).toBeEnabled();
  });

  it('shows the latest band, the probability, its meaning, and the factors with direction', async () => {
    routeGet({ '/ml/status': status(), '/machines/m1/ml-predictions': [prediction()] });
    panel();
    expect(await screen.findByText('HIGH 45%')).toBeInTheDocument();
    expect(screen.getByText(/Not a prediction for this real machine/)).toBeInTheDocument();
    expect(screen.getByRole('img', { name: /30-day failure probability 45 percent/ })).toBeInTheDocument();
    expect(screen.getByText('Tool wear')).toBeInTheDocument();
    expect(screen.getAllByLabelText('raises risk')).toHaveLength(2);
    expect(screen.getAllByLabelText('lowers risk')).toHaveLength(1);
  });

  it('shows extrapolation warnings from the service', async () => {
    routeGet({ '/ml/status': status(), '/machines/m1/ml-predictions': [prediction({ warnings: ['Temperature (400 °C) is outside the range the model was trained on.'] })] });
    panel();
    expect(await screen.findByText(/outside the range the model was trained on/)).toBeInTheDocument();
  });

  it('scores on request and then shows the new result', async () => {
    let saved: MlPrediction[] = [];
    routeGet({ '/ml/status': status(), '/machines/m1/ml-predictions': () => saved });
    apiMock.post.mockImplementation(async () => { saved = [prediction({ risk: 'Medium', probability: 0.19 })]; return ok(saved[0]); });
    panel();
    await userEvent.click(await screen.findByRole('button', { name: 'Score now' }));
    expect(apiMock.post).toHaveBeenCalledWith('/machines/m1/ml-predict');
    expect(await screen.findByText('MEDIUM 19%')).toBeInTheDocument();
    expect(screen.getByRole('button', { name: 'Score again' })).toBeInTheDocument();
  });

  it('explains when a machine cannot be scored yet, using the server\'s message', async () => {
    routeGet({ '/ml/status': status(), '/machines/m1/ml-predictions': [] });
    apiMock.post.mockRejectedValue(apiError(422, 'This machine cannot be scored yet. Missing: vibrationMms.'));
    panel();
    await userEvent.click(await screen.findByRole('button', { name: 'Score now' }));
    expect(await screen.findByRole('alert')).toHaveTextContent('Missing: vibrationMms');
  });

  it('says so when the saved result was reused because nothing changed', async () => {
    routeGet({ '/ml/status': status(), '/machines/m1/ml-predictions': [prediction()] });
    apiMock.post.mockResolvedValue(ok(prediction({ reused: true })));
    panel();
    await userEvent.click(await screen.findByRole('button', { name: 'Score again' }));
    expect(await screen.findByRole('status')).toHaveTextContent('has not changed since the last score');
  });

  it('warns that the service is unreachable and does not offer to score', async () => {
    routeGet({ '/ml/status': status({ reachable: false }), '/machines/m1/ml-predictions': [] });
    panel();
    expect(await screen.findByRole('status')).toHaveTextContent('not reachable');
    expect(screen.getByRole('button', { name: 'Score now' })).toBeDisabled();
  });

  it('opens model details with the held-out metrics, the ceiling, and every limitation', async () => {
    routeGet({ '/ml/status': status(), '/machines/m1/ml-predictions': [prediction()] });
    panel();
    await userEvent.click(await screen.findByRole('button', { name: 'About this model' }));
    expect(screen.getByText(/ROC-AUC 0.8014/)).toBeInTheDocument();
    expect(screen.getByText(/best possible from these inputs is 0.8015/)).toBeInTheDocument();
    expect(screen.getByText(/On held-out synthetic data/)).toBeInTheDocument();
    expect(screen.getByText('Trained on synthetic data generated by a documented rule set.')).toBeInTheDocument();
    expect(screen.getByText('Not validated predictions of real machine failures.')).toBeInTheDocument();
    await userEvent.click(screen.getByRole('button', { name: 'Hide model details' }));
    expect(screen.queryByText(/ROC-AUC/)).not.toBeInTheDocument();
  });
});
