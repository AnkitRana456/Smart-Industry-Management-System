import { screen, waitFor, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { beforeEach, describe, expect, it, vi } from 'vitest';
import type { Assessment } from '../lib/types';
import { apiMock, resetApi, routeGet } from '../test/mockApi';
import { apiError, machine, ok, renderWithApp } from '../test/utils';
import RiskAssessmentDialog, { RiskAssessmentSummary } from './RiskAssessment';

vi.mock('../lib/api', async () => (await import('../test/mockApi')).module);

const assessment = (over: Partial<Assessment> = {}): Assessment => ({
  assessmentId: 'a1', machineId: 'm1', riskLevel: 'HIGH',
  assessmentSummary: 'Tool wear and vibration are elevated for this machine type.',
  observedConditions: ['Tool wear is 222 min'],
  evidenceUsed: [{ field: 'toolWearMin', value: 222, unit: 'min' }, { field: 'vibrationMms', value: 4.35, unit: 'mm/s' }],
  recommendedActions: ['Ask a technician to inspect tooling at the next stop.'],
  limitations: ['Preliminary assessment generated by a language model.', 'Data issue: readings are 30 hours old.'],
  modelId: 'gemini-test', promptVersion: 'maintenance-v1', assessedAt: new Date().toISOString(), alertId: null,
  ...over,
});

const open = () => renderWithApp(<RiskAssessmentDialog machine={machine()} onClose={() => undefined} />);
const run = () => userEvent.click(screen.getByRole('button', { name: /Assess/ }));

beforeEach(() => resetApi());

describe('RiskAssessmentSummary', () => {
  it('shows the current band and when it was assessed, and opens the dialog', async () => {
    const onOpen = vi.fn();
    renderWithApp(<RiskAssessmentSummary machine={machine({ riskLevel: 'HIGH', lastAssessedAt: new Date().toISOString() })} onOpen={onOpen} />);
    expect(screen.getByText('HIGH')).toBeInTheDocument();
    expect(screen.getByText('just now')).toBeInTheDocument();
    await userEvent.click(screen.getByRole('button', { name: /Open/ }));
    expect(onOpen).toHaveBeenCalled();
  });

  it('says when a machine has never been assessed', () => {
    renderWithApp(<RiskAssessmentSummary machine={machine()} onOpen={() => undefined} />);
    expect(screen.getByText('Not assessed yet')).toBeInTheDocument();
  });
});

describe('RiskAssessmentDialog', () => {
  it('always states that this is a preliminary AI assessment, not a validated prediction', async () => {
    routeGet({ '/machines/m1/assessments': { items: [] } });
    open();
    expect(await screen.findByText(/not a validated failure prediction/i)).toBeInTheDocument();
  });

  it('starts with an empty state and an obvious action', async () => {
    routeGet({ '/machines/m1/assessments': { items: [] } });
    open();
    expect(await screen.findByText(/No assessment yet/)).toBeInTheDocument();
    expect(screen.getByRole('button', { name: 'Assess machine risk' })).toBeEnabled();
  });

  it('runs an assessment and shows the result with its evidence and limitations', async () => {
    let saved: Assessment[] = [];
    routeGet({ '/machines/m1/assessments': () => ({ items: saved }) });
    apiMock.post.mockImplementation(async () => { saved = [assessment()]; return ok(saved[0]); });
    open();
    await screen.findByText(/No assessment yet/);
    await run();

    expect(apiMock.post).toHaveBeenCalledWith('/machines/m1/assess-risk', { forceNewAssessment: false });
    expect(await screen.findByText(/Tool wear and vibration are elevated/)).toBeInTheDocument();
    expect(screen.getByText('toolWearMin')).toBeInTheDocument();
    expect(screen.getByText('222 min')).toBeInTheDocument();
    expect(screen.getByText('Ask a technician to inspect tooling at the next stop.')).toBeInTheDocument();
    expect(screen.getByText('Limitations (2)')).toBeInTheDocument();
    expect(screen.getByText(/gemini-test/)).toBeInTheDocument();
  });

  it('shows the Gemini model name, or says no model was used for a rules-only result', async () => {
    routeGet({ '/machines/m1/assessments': { items: [assessment({ riskLevel: 'INSUFFICIENT_DATA', modelId: null, evidenceUsed: [], observedConditions: [] })] } });
    open();
    expect(await screen.findByText('NO DATA')).toBeInTheDocument();
    expect(screen.getByText(/Rules check, no model used/)).toBeInTheDocument();
  });

  it('shows a clear error, says nothing was saved, and lets the user retry', async () => {
    routeGet({ '/machines/m1/assessments': { items: [] } });
    apiMock.post.mockRejectedValueOnce(apiError(503, 'The AI service is unavailable. Please try again shortly.'));
    open();
    await screen.findByText(/No assessment yet/);
    await run();

    const alert = await screen.findByRole('alert');
    expect(alert).toHaveTextContent('The AI service is unavailable');
    expect(alert).toHaveTextContent('Nothing was saved');

    apiMock.post.mockResolvedValueOnce(ok(assessment()));
    await userEvent.click(within(alert).getByRole('button', { name: 'Try again' }));
    await waitFor(() => expect(apiMock.post).toHaveBeenCalledTimes(2));
  });

  it('explains that the AI is not configured instead of failing silently', async () => {
    routeGet({ '/machines/m1/assessments': { items: [] } });
    apiMock.post.mockRejectedValueOnce(apiError(503, 'AI features are not configured on this server.'));
    open();
    await screen.findByText(/No assessment yet/);
    await run();
    expect(await screen.findByRole('alert')).toHaveTextContent('not configured');
  });

  it('keeps showing the previous assessment when a new attempt fails', async () => {
    routeGet({ '/machines/m1/assessments': { items: [assessment({ assessmentSummary: 'Earlier assessment text.' })] } });
    apiMock.post.mockRejectedValueOnce(apiError(429, 'The AI service is rate limited right now.'));
    open();
    await screen.findByText('Earlier assessment text.');
    await run();
    expect(await screen.findByRole('alert')).toHaveTextContent('rate limited');
    expect(screen.getByText('Earlier assessment text.')).toBeInTheDocument();
  });

  it('tells the user when a saved result was reused, and can force a new one', async () => {
    routeGet({ '/machines/m1/assessments': { items: [assessment()] } });
    apiMock.post.mockResolvedValue(ok(assessment({ reused: true })));
    open();
    await screen.findByText(/Tool wear and vibration/);
    await run();
    expect(await screen.findByText(/data has not changed since/)).toBeInTheDocument();
    await userEvent.click(screen.getByRole('button', { name: 'Run a new one anyway' }));
    await waitFor(() => expect(apiMock.post).toHaveBeenLastCalledWith('/machines/m1/assess-risk', { forceNewAssessment: true }));
  });

  it('links to the alert when one was raised, and not otherwise', async () => {
    routeGet({ '/machines/m1/assessments': { items: [assessment({ alertId: 'al1' })] } });
    const first = open();
    expect(await screen.findByRole('link', { name: 'Alert raised' })).toHaveAttribute('href', '/alerts');
    first.unmount();

    routeGet({ '/machines/m1/assessments': { items: [assessment({ alertId: null })] } });
    open();
    await screen.findByText(/Tool wear and vibration/);
    expect(screen.queryByRole('link', { name: 'Alert raised' })).not.toBeInTheDocument();
  });

  it('lets the user look back through the history', async () => {
    routeGet({
      '/machines/m1/assessments': {
        items: [
          assessment({ assessmentId: 'new', riskLevel: 'HIGH', assessmentSummary: 'Newest summary.', assessedAt: '2026-10-29T10:00:00Z' }),
          assessment({ assessmentId: 'old', riskLevel: 'LOW', assessmentSummary: 'Older summary.', assessedAt: '2026-10-20T10:00:00Z' }),
        ],
      },
    });
    open();
    expect(await screen.findByText('Newest summary.')).toBeInTheDocument();
    const history = within(screen.getByRole('region', { name: 'Assessment history' }));
    await userEvent.click(history.getAllByRole('button')[1]);
    expect(await screen.findByText('Older summary.')).toBeInTheDocument();
    expect(screen.queryByText('Newest summary.')).not.toBeInTheDocument();
  });
});
